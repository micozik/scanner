# -*- coding: utf-8 -*-
"""
patch_mustanswer.py  ——  放仓库【根目录】，和 scanner_cloud.py 同一层

╔══════════════════════════════════════════════════════════════════╗
║ 把三条最常被违反的铁律，★强制塞进【今日必答清单】★              ║
║ 从此每天带编号，用户数编号就知道AI漏没漏                          ║
╚══════════════════════════════════════════════════════════════════╝

★为什么必须做这个补丁（2026-09-07 实证）★
  同一份报告里：
    · 进了【今日必答清单】的 [1]~[5] → AI ★五条全答，一条没漏★
    · 只写在【固定输出骨架】里的铁律U（美股必写）→ AI ★完全没写★
  报告自己在必答清单顶上写着根因：
    「AI带着问题找答案——不问就不看，所以必然漏」
    「★机器强制，防AI漏看★」
  ★结论：规则活在文字里管不住AI，活在编号里才管得住。★

★这个补丁加三条★
  [U] ⑤-B 美股三方对照
      —— 2026-09-04 AI在没看美股的情况下砍掉存储链和CPO链。
         而9/2、9/3美股存储已连涨两天（9/3戴尔+15.76%，原话
         "缺的就是DRAM、DRAM、DRAM"），9/4夜闪迪+11%、费半+3%。
         9/7 A股半导体+133.64亿、CPO跳378位到全场第一。
         ★AI不是来不及知道，是知道了不用。★
      ★一票否决：昨夜美股该链在涨 → 今天不许给该链任何卖出建议★

  [S] 卖出三条件逐条打勾
      —— 2026-09-04 AI卖仕佳光子，实际只成立"一条半"就清仓200股。
         而系统写死要三条同时成立。
         9/7 仕佳 +8.98%、通信设备资金 +109.81亿。
      ★三条不全 → 最多减半，绝不清仓（铁律X：没有一条铁律说清仓）★

  [P] 死穴四问
      —— 博云新材死在①主营（以为硬质合金=高温合金，实际78%是碳化钨基）
         中航沈飞死在②业绩（H1净利-58.37%、市盈47.77）
         润泽科技死在③主力资金（20日-7.3亿、主力浮亏3.2%）
         山东黄金死在④驱动价格（只看人民币金价日内+2.31%，
                              实际国际金价已跌破100日均线）

★安全性★
  · 只改【今日必答清单】那一段的文字，不动任何计算逻辑
  · 幂等：装过就跳过
  · 锚点唯一性校验，不唯一就整个放弃、一个字不改
  · 改完 compile() 语法自检，★不通过自动回滚★
  · 耗时 <1 秒
"""

import io
import os

TARGET = "scanner_cloud.py"
MARK = "[U] ⑤-B 美股三方对照"

# 锚点：必答清单里那句固定的格式说明（纯中文，不含空格缩进，不依赖行首）
ANCHOR = "── AI回应格式（每条都要写）──"

ADD = """
  ══════════════════════════════════════════════════
  ★★★以下三条【每天固定必答】，与上面的编号同等效力★★★
  ★用户只要看这三个字母编号在不在回复里，就知道AI守没守规矩★
  ══════════════════════════════════════════════════

  [U] ⑤-B 美股三方对照（铁律U · 2026-09-04血案）
      必须填四个数：
        费城半导体SOX ____  美光/闪迪 ____
        英伟达 ____         美债10年期 ____
      再写三方对照：
        美股【X链】涨/跌 → A股【X链】今天涨还是跌？
        ★方向相反 = 铁律K反常 = 当场解释，不许略过★
      ★★一票否决★★
        昨夜美股该链【在涨】→ ★今天不许给该链任何卖出建议★
        要卖必须先解释"为什么美股涨而A股要卖"，解释不出就不卖
      ⚠️ 2026-09-04：AI没看美股就砍掉存储链+CPO链。
         而9/3戴尔+15.76%（原话"缺的就是DRAM"）、
         9/4闪迪+11%费半+3%。9/7 A股半导体资金+133.64亿、
         CPO跳378位全场第一。★两笔卖出少赚约2,150元★

  [S] 卖出三条件（想卖任何一只，必须逐条打勾，缺一条不许清仓）
        ① 连续≥2天资金净流出 且 累计>30亿   □是 □否
        ② ★同时★板块在跌（跌>1%）           □是 □否
        ③ 催化被官方/公司证伪               □是 □否
      ★③的证伪必须先过【证伪四问】，否则不算数：★
        1. 说话的是谁？★它在这条链的上游还是下游？★
           （下游说"供应缓解"= 上游在放量 = 对上游是利多）
        2. 这句话影响的是【量】还是【价】？两者常反向
        3. 有没有第二个独立来源？★一家公司一句话≠行业事实★
        4. 同链的美股/港股当天怎么走？对标在涨=我大概率读反了
      ★★三条不全 → 最多【减半】，绝不清仓★★
      ⚠️ 2026-09-04：AI卖仕佳光子，实际只成立"一条半"就清了200股。
         ①成立(-85亿) ②不成立(板块只跌0.44%) ③读反了方向
         9/7 仕佳 +8.98%，通信设备资金 +109.81亿

  [P] 死穴四问（推荐任何一只之前必须自己答完，答不出就要截图）
        ① 它靠什么赚钱？主营占比多少？    （博云新材死在这）
        ② 最近一期业绩，营收/净利同比？    （中航沈飞死在这）
        ③ 主力资金 3日/5日/20日，加速还是减速？（润泽科技死在这）
        ④ ★它的驱动价格此刻是涨是跌？★    （山东黄金死在这）
           —— 这一条AI自己能搜/查驱动价格表，★不搜就是失职★
      ⚠️ 缺任何一问 → 不许满仓，最多小仓试探(≤6%)
         并且必须当场向用户要那一屏截图

  ══════════════════════════════════════════════════
"""


def run():
    if not os.path.exists(TARGET):
        print("🔴 patch_mustanswer: 找不到 %s → 未修改" % TARGET)
        return

    src = io.open(TARGET, encoding="utf-8").read()

    if MARK in src:
        print("✅ patch_mustanswer: 已安装过，跳过（幂等，正常现象）")
        return

    n = src.count(ANCHOR)
    if n != 1:
        print("🔴 patch_mustanswer: 锚点出现 %d 次（需要正好1次）→ 整个放弃，未修改" % n)
        print("   锚点：%s" % ANCHOR)
        return

    i = src.find(ANCHOR)
    new_src = src[:i] + ADD + "  " + src[i:]

    try:
        compile(new_src, TARGET, "exec")
    except SyntaxError as e:
        print("🔴 patch_mustanswer: 语法检查不通过 → ★已自动回滚，原文件未动★")
        print("   %s (line %s)" % (e.msg, e.lineno))
        return

    io.open(TARGET, "w", encoding="utf-8").write(new_src)
    print("✅ patch_mustanswer: 已把 [U]美股对照 / [S]卖出三条件 / [P]死穴四问")
    print("   强制加入【今日必答清单】，语法检查通过")


try:
    run()
except Exception as e:
    print("🔴 patch_mustanswer 异常，已跳过，未修改任何文件：%s" % e)
