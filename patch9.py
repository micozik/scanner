# -*- coding: utf-8 -*-
"""V36.0 补丁 · 决策卡①-B 增加【它有几条赚钱的腿】

2026-08-28：用户给我看同花顺"问财"对亨通光电的分析，它写的是：
  『亨通光电的中线逻辑在【AI光通信高毛利】与【海缆订单兑现】
    的双重支撑下依然稳固』

★它比我强的地方只有一件事：给了两条【互相独立】的赚钱腿。
  海缆客户是运营商和电力公司，跟AI一点关系没有。
  → AI链回调时，它还有第二条腿。

★而我推的英维克只有一条腿（AI液冷）。AI一凉它就凉。
  我从头到尾只做『它在哪条链上』，从没做过『它有几条链』。

本补丁在决策卡①-B里强制加一问：
  这只票有几条【互相独立】的赚钱腿？
  单腿 → 认错线必须比双腿更紧，仓位上限更低。
"""
import io
import os

P = "scanner_cloud.py"
if not os.path.exists(P):
    print("no scanner_cloud.py")
    raise SystemExit(0)
s = io.open(P, encoding="utf-8").read()
n = 0

LEGS = [
    'w("")',
    'w("  ①-C ★★这只票有几条【互相独立】的赚钱腿？★★（V36.0新增）")',
    'w("     2026-08-28教训：同花顺问财分析亨通光电，写的是")',
    'w("       『在【AI光通信高毛利】与【海缆订单兑现】双重支撑下』")',
    'w("     ★海缆客户是运营商和电力公司，跟AI一点关系没有")',
    'w("       → AI链回调时，它还有第二条腿撑着")',
    'w("     ★而我推的英维克只有一条腿(AI液冷)，AI一凉它就凉。")',
    'w("       我一直只做『它在哪条链上』，从没做过『它有几条链』。")',
    'w("")',
    'w("     必须填：")',
    'w("       腿① ____________（占营收约__%，客户是谁）")',
    'w("       腿② ____________（★必须和腿①的下游完全不同★）")',
    'w("       腿③ ____________（有就填，没有写『无』）")',
    'w("")',
    'w("     ⚠️【判定标准】两条腿的下游客户必须不同：")',
    'w("       ✅真双腿：AI数据中心 + 海底光缆（客户完全不同）")',
    'w("       ❌假双腿：AI液冷 + 储能温控（都是温控，同一个能力）")',
    'w("       ❌假双腿：存储模组 + 存储分销（同一条链的上下游）")',
    'w("")',
    'w("     ⚠️【仓位与认错线，按腿数分档】")',
    'w("       ★双腿以上：仓位可到18-20%，认错线可给到-8%")',
    'w("       ★单腿标的：仓位≤11%，★认错线收紧到-3%★")',
    'w("         理由：单腿票的驱动一旦有反向证据，没有第二条腿接着，")',
    'w("               下跌是直线的，不给你缓冲时间。")',
    'w("")',
]

A = "  ① 板块第几天？🆕第1天 | 连2天 | 🔥连≥5天"
if A in s and "①-C" not in s:
    idx = s.find(A)
    ls = s.rfind("\n", 0, idx) + 1
    block = "\n".join("    " + x for x in LEGS)
    s = s[:ls] + block + "\n" + s[ls:]
    n += 1
    print("OK 1: 决策卡①-C【几条腿】已插入")
else:
    print("SKIP 1")

# 今日唯一决断卡也加这一问
B = 'w("     b) 今日硬证据：____________（真实订单/涨价/扩产/中标）")'
C = ('w("     b) 今日硬证据：____________（真实订单/涨价/扩产/中标）")\n'
     '    w("     b2) ★它有几条独立的赚钱腿？★（V36.0）")\n'
     '    w("        单腿 → 仓位≤11%、认错线-3%")\n'
     '    w("        双腿 → 仓位可18-20%、认错线-8%")\n'
     '    w("        ⚠️两条腿的【下游客户】必须完全不同才算数")')
if B in s and "b2)" not in s:
    s = s.replace(B, C, 1)
    n += 1
    print("OK 2: 今日唯一决断卡已加")
else:
    print("SKIP 2")

if "V35.0 |" in s:
    s = s.replace("A股作战扫描器V35.0 |", "A股作战扫描器V36.0 |")
    n += 1

if n:
    io.open(P, "w", encoding="utf-8").write(s)
    print("DONE: %d changes" % n)
else:
    print("DONE: nothing")
